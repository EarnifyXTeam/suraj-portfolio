const contactForm = document.getElementById('contactForm');
const submitBtn = document.getElementById('submitBtn');
const formSuccessAlert = document.getElementById('formSuccessAlert');

if (contactForm && submitBtn && formSuccessAlert) {
  contactForm.addEventListener('submit', (e) => {
    e.preventDefault();

    const originalText = submitBtn.innerHTML;
    submitBtn.disabled = true;
    const sendingText = currentLang === 'hi' ? 'भेजा जा रहा है...' : 'Sending...';
    submitBtn.innerHTML = `<i class="fa-solid fa-spinner fa-spin"></i> <span>${sendingText}</span>`;

    setTimeout(() => {
      submitBtn.disabled = false;
      submitBtn.innerHTML = originalText;

      formSuccessAlert.classList.remove('hidden');
      contactForm.reset();

      setTimeout(() => {
        formSuccessAlert.classList.add('hidden');
      }, 6000);
    }, 800);
  });
}
